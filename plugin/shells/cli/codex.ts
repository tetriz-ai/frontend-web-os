// fwos's agents for Codex. Codex reads skills and hooks from the plugin, but custom agents only
// from `.codex/agents/*.toml`, so fwos writes one per agent it ships, generated from the same .md
// files Claude Code reads: there's no second copy in this repo. Each holds this machine's plugin
// folder, so the files are git-ignored, and every machine writes its own (`fwos codex agents`).

import { readdirSync } from 'node:fs';
import { posix } from 'node:path';
import { FwosError, parseFrontmatter, pluginRoot, pluginVersion, readJson, readText, writeText } from '../../kernel/index.ts';

export const cliOnlyDistribution = () => (globalThis as Record<symbol, unknown>)[Symbol.for('fwos.cliOnlyDistribution')] === true;

export const CODEX_AGENTS_DIR = '.codex/agents';
const PREFIX = 'fwos-';
const HEADER = '# generated by fwos, do not edit. Rewrite with `fwos codex agents`.';
const IGNORE = `${CODEX_AGENTS_DIR}/${PREFIX}*.toml`;

export interface CodexAgentFile {
  /** The agent's name: Codex spawns it by this, and fwos's skills and hooks use the same one. */
  name: string;
  /** Where it goes in the project. */
  path: string;
  content: string;
}

/** A TOML string for any text: a literal block when it can be one, else a basic string. */
function tomlString(text: string): string {
  return text.includes("'''") || /[\u0000-\u0008\u000b-\u001f]/.test(text) ? JSON.stringify(text) : `'''\n${text}'''`;
}

/** The Codex agent files for every agent the plugin ships, read from the Claude Code manifest. */
export function codexAgentFiles(root: string = pluginRoot): CodexAgentFile[] {
  if (cliOnlyDistribution() && root === pluginRoot) throw new FwosError('This npm distribution contains the checks CLI, without host agents.', 'Run `fwos codex agents` with the full installed plugin CLI: node <plugin>/dist/fwos.mjs codex agents.');
  const manifest = readJson<{ agents?: string[] }>(posix.join(root, '.claude-plugin', 'plugin.json'));
  if (!manifest?.agents) {
    throw new FwosError(`No agents found in ${posix.join(root, '.claude-plugin', 'plugin.json')}.`, "Run this with the plugin's own CLI (`node <plugin>/dist/fwos.mjs codex agents`), not a vendored copy.");
  }
  return manifest.agents.map((rel) => {
    const text = readText(posix.join(root, rel));
    if (text === null) throw new FwosError(`The plugin is missing ${rel}.`, 'Reinstall the plugin.');
    const { data, body } = parseFrontmatter(text);
    const name = String(data.name ?? posix.basename(rel, '.md'));
    const tools = String(data.tools ?? '');
    // Codex has no per-agent tool list: an agent that may write or run commands gets a writable
    // workspace, the rest read only. fwos's hooks still deny the test planner every tool.
    const sandbox = /\b(Write|Edit|Bash)\b/.test(tools) ? 'workspace-write' : 'read-only';
    const skills = Array.isArray(data.skills) ? data.skills.map(String) : [];
    const instructions = [
      body.trim().replaceAll('${CLAUDE_PLUGIN_ROOT}', root),
      ...(skills.length > 0 ? [`Before you start, read the ${skills.map((s) => `\`${s}\``).join(', ')} skill${skills.length === 1 ? '' : 's'}.`] : []),
    ].join('\n\n');
    const content = [
      HEADER,
      `# source: ${rel} in fwos ${pluginVersion()} at ${root}`,
      `name = ${JSON.stringify(name)}`,
      `description = ${JSON.stringify(String(data.description ?? ''))}`,
      `sandbox_mode = "${sandbox}"`,
      `developer_instructions = ${tomlString(`${instructions}\n`)}`,
      '',
    ].join('\n');
    return { name, path: posix.join(CODEX_AGENTS_DIR, `${PREFIX}${name}.toml`), content };
  });
}

export interface CodexAgentsStatus {
  /** fwos agent files in the project. */
  found: number;
  expected: number;
  /** Files that differ from what this plugin would write (another version or folder), or are missing. */
  stale: string[];
}

export function codexAgentsStatus(projectRoot: string, root: string = pluginRoot): CodexAgentsStatus {
  const files = codexAgentFiles(root);
  const dir = posix.join(projectRoot, CODEX_AGENTS_DIR);
  let present: string[] = [];
  try {
    present = readdirSync(dir).filter((f) => f.startsWith(PREFIX) && f.endsWith('.toml'));
  } catch {
    present = [];
  }
  const stale = files.filter((f) => readText(posix.join(projectRoot, f.path)) !== f.content).map((f) => f.path);
  return { found: present.length, expected: files.length, stale };
}

/** Writes the agent files and git-ignores them. Refuses to replace a file fwos didn't write. */
export function writeCodexAgents(projectRoot: string, root: string = pluginRoot): { written: string[]; unchanged: string[] } {
  const written: string[] = [];
  const unchanged: string[] = [];
  for (const f of codexAgentFiles(root)) {
    const abs = posix.join(projectRoot, f.path);
    const now = readText(abs);
    if (now === f.content) {
      unchanged.push(f.path);
      continue;
    }
    if (now !== null && !now.startsWith(HEADER)) {
      throw new FwosError(`${f.path} already exists and fwos didn't write it, so it won't overwrite it.`, 'Rename or delete it, then run `fwos codex agents` again.');
    }
    try {
      writeText(abs, f.content);
    } catch (e) {
      // Codex's sandbox keeps .codex/ (and .git/) read-only, even when the workspace is writable.
      if (['EPERM', 'EACCES', 'EROFS'].includes((e as NodeJS.ErrnoException).code ?? '')) {
        throw new FwosError(
          `Couldn't write ${CODEX_AGENTS_DIR}/: ${inCodex() ? "Codex's sandbox keeps .codex/ read-only" : 'permission denied'}.`,
          `Approve running it outside the sandbox when Codex asks, or run it in a terminal in this folder: node "${posix.join(root, 'dist', 'fwos.mjs')}" codex agents`,
        );
      }
      throw e;
    }
    written.push(f.path);
  }
  ignoreCodexAgents(projectRoot);
  return { written, unchanged };
}

/** Adds the generated agents to the project's .gitignore, once. */
function ignoreCodexAgents(projectRoot: string): void {
  const path = posix.join(projectRoot, '.gitignore');
  const text = readText(path) ?? '';
  if (text.split('\n').some((l) => l.trim() === IGNORE)) return;
  const sep = text === '' || text.endsWith('\n') ? '' : '\n';
  writeText(path, `${text}${sep}# fwos: its agents for Codex hold this machine's plugin folder\n${IGNORE}\n`);
}

/** Whether this process runs inside a Codex session (Codex sets these in its shell). */
export function inCodex(env: NodeJS.ProcessEnv = process.env): boolean {
  return !!(env.CODEX_THREAD_ID || env.CODEX_SESSION_ID);
}

