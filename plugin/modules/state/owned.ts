// Ownership. [generated] and [fwos] files are listed in `.fwos/manifest.json` with the checksum
// fwos last wrote; if yours differs, fwos stops and names the file. A command that writes many can
// ask what each write would do first, and write none while one is refused, after copying what it
// replaces to `.fwos/local/backup/`. [yours] files fwos wrote are recorded in
// `.fwos/provenance.json` and never touched again.

import { copyFileSync, existsSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import {
  FwosError,
  ownedPath,
  hashText,
  isFile,
  pluginVersion,
  readJson,
  readText,
  writeJson,
  writeText,
} from '../../kernel/index.ts';
import { now } from './model.ts';
import { FWOS_DIR } from './store.ts';
export { ownedPath } from '../../kernel/index.ts';

export interface ManifestEntry {
  sha: string;
  kind: 'generated' | 'fwos';
  source?: string;
  pluginVersion: string;
}

export interface Manifest {
  schema: 1;
  files: Record<string, ManifestEntry>;
}

export function readManifest(root: string): Manifest {
  ownedPath(root, `${FWOS_DIR}/state.json`);
  return readJson<Manifest>(ownedPath(root, `${FWOS_DIR}/manifest.json`)) ?? { schema: 1, files: {} };
}

function writeManifest(root: string, m: Manifest): void {
  if (!isFile(ownedPath(root, `${FWOS_DIR}/state.json`))) return; // not an fwos project (e.g. a dry run)
  writeJson(ownedPath(root, `${FWOS_DIR}/manifest.json`), m);
}

export const GENERATED_HEADER = 'generated by fwos, do not edit';

export interface OwnedWrite {
  path: string;
  status: 'written' | 'unchanged';
}

/**
 * What writing `content` to the file fwos owns at `rel` would do: `new` (nothing there yet),
 * `unchanged`, `replace` (it holds what fwos last wrote), or one of the two refusals: `edited`
 * (changed since fwos wrote it) and `foreign` (a file fwos didn't write sits there).
 */
export type OwnedStatus = 'new' | 'unchanged' | 'replace' | 'edited' | 'foreign';

export function ownedStatus(root: string, rel: string, content: string, manifest: Manifest = readManifest(root)): OwnedStatus {
  const onDisk = readText(ownedPath(root, rel));
  if (onDisk === null) return 'new';
  const diskSha = hashText(onDisk);
  if (diskSha === hashText(content)) return 'unchanged';
  const entry = manifest.files[rel];
  if (!entry) return 'foreign';
  return entry.sha === diskSha ? 'replace' : 'edited';
}

/**
 * Writes a file fwos owns. Refuses when the file on disk isn't what fwos last wrote (someone
 * edited it), or when an unrelated file already sits at that path.
 */
export function writeOwned(
  root: string,
  rel: string,
  content: string,
  kind: ManifestEntry['kind'],
  source?: string,
): OwnedWrite {
  const manifest = readManifest(root);
  const entry = manifest.files[rel];
  const sha = hashText(content);
  const status = ownedStatus(root, rel, content, manifest);
  if (status === 'foreign' || status === 'edited') throw refusal(rel, status, entry);
  if (status === 'unchanged') {
    if (!entry || entry.sha !== sha) {
      manifest.files[rel] = { sha, kind, pluginVersion: pluginVersion(), ...(source ? { source } : {}) };
      writeManifest(root, manifest);
    }
    return { path: rel, status: 'unchanged' };
  }
  writeText(ownedPath(root, rel), content);
  manifest.files[rel] = { sha, kind, pluginVersion: pluginVersion(), ...(source ? { source } : {}) };
  writeManifest(root, manifest);
  return { path: rel, status: 'written' };
}

/** Why fwos won't write an owned file: one fwos didn't write sits there, or it was edited by hand. */
function refusal(rel: string, status: 'foreign' | 'edited', entry?: ManifestEntry): FwosError {
  if (status === 'foreign') {
    return new FwosError(`${rel} already exists and fwos didn't write it, so it won't overwrite it.`, 'Move or delete the file, then run the command again.');
  }
  return new FwosError(
    `${rel} was edited by hand since fwos generated it, so it won't overwrite it.`,
    `It's generated${entry?.source ? ` from ${entry.source}` : ''}. Put the change in the source, delete ${rel}, and run the command again.`,
  );
}

/**
 * Writes a set of files fwos owns, all or none: each write is asked about first, and one refused
 * stops them all, so a set such as the token CSS and its Tailwind theme never ends up half new.
 */
export function writeOwnedAll(root: string, files: { path: string; content: string; source?: string }[], kind: ManifestEntry['kind']): OwnedWrite[] {
  const manifest = readManifest(root);
  for (const f of files) {
    const status = ownedStatus(root, f.path, f.content, manifest);
    if (status === 'foreign' || status === 'edited') throw refusal(f.path, status, manifest.files[f.path]);
  }
  return files.map((f) => writeOwned(root, f.path, f.content, kind, f.source));
}

/**
 * Deletes a file fwos owns, and its manifest entry: one a newer fwos no longer ships. Refuses one
 * edited since fwos wrote it. A file that is already gone only loses its entry.
 */
export function removeOwned(root: string, rel: string): void {
  const manifest = readManifest(root);
  const entry = manifest.files[rel];
  const onDisk = readText(ownedPath(root, rel));
  if (onDisk !== null && entry && hashText(onDisk) !== entry.sha) {
    throw new FwosError(`${rel} was edited by hand since fwos wrote it, so it won't delete it.`, 'Restore it, or move your change somewhere fwos reads it, then run the command again.');
  }
  if (onDisk !== null) rmSync(ownedPath(root, rel));
  delete manifest.files[rel];
  writeManifest(root, manifest);
}

/**
 * Copies each file that exists among `rels` (relative to the root) into a new folder under
 * `.fwos/local/backup/`, at the same relative path, before a command replaces or removes it.
 * Returns that folder, relative to the root, or null when there was nothing to copy.
 */
export function backupFiles(root: string, rels: string[]): string | null {
  const paths = rels.map((rel) => ({ rel, abs: ownedPath(root, rel) }));
  const present = paths.filter(({ abs }) => isFile(abs));
  if (present.length === 0) return null;
  const stamp = now().replace(/[:.]/g, '-');
  let dir = posix.join(FWOS_DIR, 'local', 'backup', stamp);
  for (let n = 2; existsSync(ownedPath(root, dir)); n++) dir = posix.join(FWOS_DIR, 'local', 'backup', `${stamp}-${n}`);
  const copies = present.map(({ rel, abs }) => ({ from: abs, to: ownedPath(root, posix.join(dir, rel)) }));
  for (const { from, to } of copies) {
    mkdirSync(dirname(to), { recursive: true });
    copyFileSync(from, to);
  }
  return dir;
}

/** Owned files whose content no longer matches the manifest (hand edits). */
export function editedOwnedFiles(root: string): string[] {
  const m = readManifest(root);
  return Object.entries(m.files)
    .filter(([rel, e]) => {
      const text = readText(ownedPath(root, rel));
      return text !== null && hashText(text) !== e.sha;
    })
    .map(([rel]) => rel);
}

export interface ProvenanceEntry {
  path: string;
  at: string;
  pluginVersion: string;
  by: string;
}

/** Writes a file that becomes yours. Never overwrites. Returns false if the file was already there. */
export function writeYours(root: string, rel: string, content: string, by: string): boolean {
  const abs = ownedPath(root, rel);
  if (isFile(abs)) return false;
  writeText(abs, content);
  const path = ownedPath(root, `${FWOS_DIR}/provenance.json`);
  const ledger = readJson<{ schema: 1; entries: ProvenanceEntry[] }>(path) ?? { schema: 1, entries: [] };
  ledger.entries.push({ path: rel, at: now(), pluginVersion: pluginVersion(), by });
  if (isFile(ownedPath(root, `${FWOS_DIR}/state.json`))) writeJson(path, ledger);
  return true;
}
