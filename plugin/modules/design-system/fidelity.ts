/** Where `fwos design-system decide` records decisions. fwos's record: the edit tools can't write it. */
export const FIDELITY_RECORD = '.fwos/fidelity.json';

export type Decision = 'replace' | 'omit' | 'intentional';
export const DECISIONS: Decision[] = ['replace', 'omit', 'intentional'];

export interface DecisionRecord {
  item: string;
  decision: Decision;
  reason: string;
  by: string;
  at: string;
  /** The hash of what was decided: once it changes, the decision no longer covers it. */
  seen: string;
}

/** The report `fwos design-system report` writes, next to the acceptance report. */
export const designSystemReportPath = (p: Project) => posix.join(p.paths.docs, 'reports', 'design-system.md');

export const REPORT_HEADER = '<!-- generated by `fwos design-system report`; do not edit. It is rebuilt from design-system/, the decisions in .fwos/fidelity.json and the last gallery run. -->';

/** The viewports the gallery renders at: a phone and a desktop. */
export const VIEWPORTS = [
  { name: 'phone', width: 390, height: 844 },
  { name: 'desktop', width: 1280, height: 800 },
];

// ---- the gallery model ------------------------------------------------------------------------

/** A slot's CSS variables in a mode, as the token build writes them: a fallback to another slot stays a var(). */
function slotVars(slot: ResolvedSlot | undefined, mode: string): [string, string][] {
  if (!slot) return [];
  const name = cssVar(slot.def.id);
  if (slot.status === 'blank') return [[name, 'initial']];
  if (slot.status === 'default' && typeof slot.from === 'string' && slot.from.startsWith('@')) return [[name, `var(${cssVar(slot.from.slice(1))})`]];
  return (slot.css[mode] ?? []).map((d) => [`${name}${d.suffix}`, d.value]);
}

/**
 * The variables each side sets, per mode. Adopted: every slot as the design system holds it, and,
 * for a shadcn theme, each of its variables reading the slot that took it (`initial` when none did).
 * Original: the theme's own variables, and each slot as the theme gives it, so fwos's components
 * show the theme's values. A slot the source has nothing for shows fwos's value on both sides:
 * there is nothing to compare it with, and its row says so.
 */
function sideVariables(m: Mapping): Pick<GalleryModel, 'variables' | 'rows'> {
  const rows: Record<string, string> = { '--fwos-gallery-bg': 'surface.base', '--fwos-gallery-fg': 'text.primary' };
  const original: Record<string, Record<string, string>> = {};
  const adopted: Record<string, Record<string, string>> = {};
  const fromSource = new Set(m.tokens.filter((t) => t.target && t.source).map((t) => t.target!));
  for (const mode of m.modes) {
    const a: Record<string, string> = {};
    const o: Record<string, string> = {};
    for (const def of SLOTS) {
      const mine = slotVars(m.ds.slots.get(def.id), mode);
      const theirs = m.theme && fromSource.has(def.id) ? slotVars(m.theme.imported.get(def.id), mode) : mine;
      for (const [k, v] of mine) {
        a[k] = v;
        rows[k] = def.id;
      }
      for (const [k, v] of theirs) {
        o[k] = v;
        rows[k] = def.id;
      }
    }
    for (const [name, value] of Object.entries(m.theme?.vars[mode] ?? {})) {
      const slot = m.theme!.takenBy[name];
      o[name] = value;
      a[name] = slot ? `var(${cssVar(slot)})` : 'initial';
      rows[name] = slot ?? name;
    }
    for (const side of [a, o]) {
      side['--fwos-gallery-bg'] = `var(${cssVar('surface.base')})`;
      side['--fwos-gallery-fg'] = `var(${cssVar('text.primary')})`;
    }
    original[mode] = o;
    adopted[mode] = a;
  }
  return { variables: { original, adopted }, rows };
}

/** What renders on each side for each installed component. One that isn't installed has nothing to render yet. */
function entries(project: Project, m: Mapping, adapters: AdapterSet): GalleryEntry[] {
  const { gallery } = componentAdapters(project, adapters);
  if (!gallery) return [];
  const out: GalleryEntry[] = [];
  for (const row of m.components) {
    if (row.status === 'preserved' && row.facts) out.push({ id: row.key, kind: 'reused', original: row.facts, adopted: row.facts });
    else if (row.status === 'defaulted' && row.target?.file && row.facts) out.push({ id: row.key, kind: 'starter', original: row.facts, adopted: row.facts });
    else if (row.status === 'approximated' && row.facts && row.target?.file) {
      const next = gallery.describe(project, { id: row.target.id, file: row.target.file, source: row.target.by === 'fwos' ? 'fwos' : 'local' }, []);
      out.push({ id: row.key, kind: 'replaced', original: row.facts, adopted: next });
    } else if (row.status === 'unsupported' && row.facts) out.push({ id: row.key, kind: 'omitted', original: row.facts, adopted: null });
  }
  return out;
}

/** The comparison gallery for the project's adopted design system. Refuses the neutral starter: there is no source. */
export function galleryModel(project: Project, adapters: AdapterSet, mapping?: Mapping): GalleryModel {
  const m = mapping ?? mapDesignSystem(project, adapters);
  if (!m) throw new FwosError('No design-system/design-system.json.', 'Run `fwos design-system init` first (add `--from-shadcn <globals.css>` to start from your theme).');
  if (m.input === 'starter') {
    throw new FwosError(
      'There is nothing to compare: nothing was adopted, and the design system is the neutral starter.',
      'The gallery compares an adopted design system with its source: a shadcn theme (`fwos design-system init --from-shadcn`) or your own DTCG tokens.',
    );
  }
  return {
    schema: 1,
    name: m.name,
    modes: m.modes,
    dark: m.modes.includes('dark') ? 'dark' : null,
    viewports: VIEWPORTS,
    ...sideVariables(m),
    components: entries(project, m, adapters),
  };
}

// ---- results ----------------------------------------------------------------------------------

type ResultsState = { state: 'none'; reason: string } | { state: 'stale'; results: FidelityResults } | { state: 'current'; results: FidelityResults };

/** The last gallery run, and whether it rendered this model with these files: `expected` is the hash a current run carries. */
function readResults(project: Project, model: GalleryModel | null, expected: string | null): ResultsState {
  const text = readText(project.abs(FIDELITY_RESULTS));
  if (text === null) return { state: 'none', reason: 'no rendered comparison yet' };
  let data: FidelityResults;
  try {
    data = parseJsonc(text) as FidelityResults;
  } catch {
    return { state: 'none', reason: `${FIDELITY_RESULTS} isn't valid JSON` };
  }
  if (data?.schema !== 1 || !Array.isArray(data.cells) || typeof data.gallery !== 'string') return { state: 'none', reason: `${FIDELITY_RESULTS} isn't a gallery run fwos recognises` };
  if (!model || data.gallery !== expected) return { state: 'stale', results: data };
  const key = (c: { component: string; cell: string; mode: string; viewport: string }) => JSON.stringify([c.component, c.cell, c.mode, c.viewport]);
  const expectedCells = new Set(model.components.flatMap((c) => [...new Set([...(c.original?.cells ?? []), ...(c.adopted?.cells ?? [])].map((cell) => cell.id))].flatMap((cell) => model.modes.flatMap((mode) => model.viewports.map((v) => key({ component: c.id, cell, mode, viewport: v.name }))))));
  const seen = new Set<string>();
  for (const cell of data.cells) {
    if (!cell || !Array.isArray(cell.differences) || !Array.isArray(cell.behaviour) || !expectedCells.has(key(cell)) || seen.has(key(cell))) return { state: 'none', reason: 'the gallery results contain malformed, duplicate or unexpected cells' };
    seen.add(key(cell));
  }
  if (expectedCells.size === 0 || seen.size !== expectedCells.size) return { state: 'none', reason: `the gallery results cover ${seen.size} of ${expectedCells.size} required cells; a complete rendered comparison is required` };
  if (!Array.isArray(data.errors) || data.errors.some((error) => typeof error !== 'string')) return { state: 'none', reason: 'the gallery results have no valid error list' };
  return { state: 'current', results: data };
}

// ---- decisions --------------------------------------------------------------------------------

/** The decisions recorded so far, oldest item first. Throws on a malformed record, rather than drop it. */
export function readDecisions(project: Project): DecisionRecord[] {
  const text = readText(project.abs(FIDELITY_RECORD));
  if (text === null) return [];
  let data: unknown;
  try {
    data = parseJsonc(text);
  } catch (e) {
    throw new FwosError(`${FIDELITY_RECORD} isn't valid JSON: ${(e as Error).message}`, 'Restore it from git: decisions are recorded with `fwos design-system decide`.');
  }
  const errors = validateWith(fidelitySchema, data);
  if (errors.length > 0) throw new FwosError(`${FIDELITY_RECORD} is malformed: ${errors.join('; ')}`, 'Restore it from git: decisions are recorded with `fwos design-system decide`.');
  return (data as { decisions: DecisionRecord[] }).decisions;
}

/** Something that needs a decision: a row, a component, or a rendered difference no row accounts for. */
export interface Item {
  item: string;
  kind: 'token' | 'component' | 'render';
  status: RowStatus | 'render';
  /** The decisions that settle it. None: only a clean run settles it (page errors). */
  needs: Decision[];
  what: string;
  /** The hash of what would be decided. */
  seen: string;
}

const hashOf = (v: unknown) => hashText(JSON.stringify(v));

/** A rendered difference, and what accounts for it: the rows behind its causes, or nothing. */
interface Difference {
  component: string;
  cell: FidelityCell;
  property: string;
  element: string;
  original: string;
  adopted: string;
  /** The rows its causes come from; empty when nothing accounts for it. */
  rows: string[];
}

interface Rendered {
  /** Per component: cells compared on both sides, and how many rendered the same. */
  summary: Map<string, { kind: GalleryEntry['kind']; cells: number; same: number; behaviour: number }>;
  differences: Difference[];
  behaviour: { component: string; cell: FidelityCell; interaction: string; original: string; adopted: string }[];
  /** Components whose differences nothing accounts for. */
  unexplained: Map<string, string[]>;
  errors: string[];
}

/** What the last run found, with each difference traced to the rows behind it. */
function rendered(model: GalleryModel, results: FidelityResults, tokens: Map<string, TokenRow>): Rendered {
  const summary: Rendered['summary'] = new Map(model.components.map((c) => [c.id, { kind: c.kind, cells: 0, same: 0, behaviour: 0 }]));
  const differences: Difference[] = [];
  const behaviour: Rendered['behaviour'] = [];
  const unexplained = new Map<string, string[]>();
  const flag = (component: string, why: string) => unexplained.set(component, [...(unexplained.get(component) ?? []), why]);
  for (const cell of results.cells) {
    const s = summary.get(cell.component);
    if (!s) continue;
    s.cells++;
    const changedBehaviour = cell.behaviour.filter((b) => b.original !== b.adopted);
    if (cell.differences.length === 0 && changedBehaviour.length === 0 && !cell.missing) s.same++;
    // Yours replaced or left out: its component decision covers how it renders.
    const covered = s.kind === 'replaced' || s.kind === 'omitted';
    if (cell.missing && !covered) flag(cell.component, `${cell.cell} didn't render on the ${cell.missing} side`);
    for (const d of cell.differences) {
      const rows = [...new Set(d.causes.map((v) => model.rows[v]).filter((r): r is string => !!r))];
      // A cause on a preserved row can't differ between the sides: nothing then accounts for it.
      const accounted = d.causes.length > 0 && d.causes.every((v) => !!model.rows[v]) && rows.every((r) => (tokens.get(r)?.status ?? 'preserved') !== 'preserved');
      differences.push({ component: cell.component, cell, property: d.property, element: d.element, original: d.original, adopted: d.adopted, rows: accounted ? rows : [] });
      if (!accounted && !covered) flag(cell.component, `${d.property} in ${cell.cell}`);
    }
    for (const b of changedBehaviour) {
      s.behaviour++;
      behaviour.push({ component: cell.component, cell, ...b });
      if (!covered) flag(cell.component, `${b.interaction} in ${cell.cell}`);
    }
  }
  return { summary, differences, behaviour, unexplained, errors: results.errors ?? [] };
}

interface Assessment {
  mapping: Mapping;
  model: GalleryModel | null;
  results: ResultsState;
  render: Rendered | null;
  items: Item[];
  decisions: DecisionRecord[];
  /** Items with no decision that settles them, a decision made before they changed included. */
  unresolved: Item[];
  /** Decisions about something that has changed since, or no longer exists. */
  stale: DecisionRecord[];
  orphans: DecisionRecord[];
  command: string | null;
}

function assess(project: Project, adapters: AdapterSet, mapping?: Mapping): Assessment {
  const m = mapping ?? mapDesignSystem(project, adapters);
  if (!m) throw new FwosError('No design-system/design-system.json.', 'Run `fwos design-system init` first (add `--from-shadcn <globals.css>` to start from your theme).');
  const { gallery } = componentAdapters(project, adapters);
  const model = m.input === 'starter' ? null : galleryModel(project, adapters, m);
  const expected = model ? (gallery ? gallery.hash(project, model) : galleryHash(model)) : null;
  const results = m.input === 'starter' ? ({ state: 'none', reason: 'nothing adopted' } as const) : readResults(project, model, expected);
  const tokens = new Map(m.tokens.map((t) => [t.key, t]));
  const render = model && results.state === 'current' ? rendered(model, results.results, tokens) : null;
  const items: Item[] = [];
  if (m.input !== 'starter') {
    for (const t of m.tokens) {
      if (t.status === 'preserved') continue;
      items.push({ item: t.key, kind: 'token', status: t.status, needs: ['intentional'], what: `${t.status}${t.why ? `: ${t.why}` : ''}`, seen: hashOf([t.status, t.original, t.result]) });
    }
    for (const c of m.components) {
      if (c.status === 'preserved') continue;
      items.push({
        item: c.key,
        kind: 'component',
        status: c.status,
        needs: c.status === 'unsupported' ? ['omit'] : ['replace'],
        what: `${c.status}: ${c.why}`,
        seen: hashOf([c.status, c.source?.file ?? null, c.target?.id ?? null, c.target?.file ?? null]),
      });
    }
    for (const [component, why] of render?.unexplained ?? []) {
      const seen = hashOf([
        render!.differences.filter((d) => d.component === component).map((d) => [d.cell.cell, d.cell.mode, d.cell.viewport, d.element, d.property, d.original, d.adopted]),
        render!.behaviour.filter((b) => b.component === component).map((b) => [b.cell.cell, b.cell.mode, b.cell.viewport, b.interaction, b.original, b.adopted]),
      ]);
      items.push({ item: `render:${component}`, kind: 'render', status: 'render', needs: ['intentional'], what: `nothing accounts for ${why.length === 1 ? why[0] : `${why[0]} and ${why.length - 1} more`}`, seen });
    }
    if (render && render.errors.length > 0) {
      items.push({ item: 'render:errors', kind: 'render', status: 'render', needs: [], what: `the pages threw ${render.errors.length === 1 ? 'an error' : `${render.errors.length} errors`} during the run: fix them and run it again`, seen: hashOf(render.errors) });
    }
  }
  const decisions = readDecisions(project);
  const byItem = new Map(decisions.map((d) => [d.item, d]));
  const unresolved = items.filter((i) => {
    const d = byItem.get(i.item);
    return !d || !i.needs.includes(d.decision) || d.seen !== i.seen;
  });
  const known = new Map(items.map((i) => [i.item, i]));
  const stale = decisions.filter((d) => known.has(d.item) && known.get(d.item)!.seen !== d.seen);
  // A render decision outlives a run that is out of date: it only lapses once a current run disagrees.
  const orphans = decisions.filter((d) => !known.has(d.item) && !(d.item.startsWith('render:') && !render));
  return { mapping: m, model, results, render, items, decisions, unresolved, stale, orphans, command: gallery ? gallery.command(project) : null };
}

const GROUPS = new Set<RowStatus>(['approximated', 'defaulted', 'unsupported', 'changed']);

/**
 * Records `decision` for each item: a row's key, a component's id, `render:<component>`, or a
 * status, which takes every undecided item of that status the decision fits. Throws, recording
 * nothing, on an item that isn't there or a decision that doesn't fit it.
 */
export function decide(project: Project, adapters: AdapterSet, items: string[], decision: Decision, reason: string, by: string, at = new Date().toISOString()): DecisionRecord[] {
  if (!DECISIONS.includes(decision)) throw new FwosError(`--as must be replace, omit or intentional, not "${decision}".`);
  if (!reason.trim()) throw new FwosError('A decision needs a reason: --reason "<why>".');
  if (!by.trim()) throw new FwosError('A decision needs a name: --by "<who decided>".');
  if (items.length === 0) throw new FwosError('Name what you decide: a row, a component, `render:<component>` or a status.', '`fwos design-system report` lists what needs a decision.');
  const a = assess(project, adapters);
  if (a.mapping.input === 'starter') throw new FwosError('There is nothing to decide: nothing was adopted, and the design system is the neutral starter.');
  const open = new Set(a.unresolved.map((i) => i.item));
  const chosen: Item[] = [];
  for (const name of items) {
    if (GROUPS.has(name as RowStatus)) {
      const all = a.items.filter((i) => i.status === name && i.needs.includes(decision) && open.has(i.item));
      if (all.length === 0) throw new FwosError(`No undecided item is ${name} and takes ${decision}.`, '`fwos design-system report` lists what needs a decision.');
      chosen.push(...all);
      continue;
    }
    const item = a.items.find((i) => i.item === name);
    if (!item) {
      const token = a.mapping.tokens.find((t) => t.key === name);
      const comp = a.mapping.components.find((c) => c.key === name);
      if (token?.status === 'preserved') throw new FwosError(`${name} is preserved: there is nothing to decide.`);
      if (comp?.status === 'preserved') throw new FwosError(`${name} is yours, reused as it is: there is nothing to decide.`);
      throw new FwosError(`No row, component or difference is called "${name}".`, '`fwos design-system report` lists what needs a decision.');
    }
    if (item.needs.length === 0) throw new FwosError(`${name} can't be decided: ${item.what}.`);
    if (item.kind === 'token' && decision !== 'intentional') throw new FwosError(`${name} is a token: decide intentional, with what makes the difference acceptable.`);
    if (item.kind === 'render' && decision !== 'intentional') throw new FwosError(`${name} is a rendered difference: decide intentional, with what makes it acceptable.`);
    if (item.kind === 'component' && decision === 'intentional') throw new FwosError(`${name} is a component: decide replace or omit.`);
    if (!item.needs.includes(decision)) throw new FwosError(`${name} is ${item.what}: decide ${item.needs.join(' or ')}.`);
    chosen.push(item);
  }
  const made = chosen.map((i): DecisionRecord => ({ item: i.item, decision, reason: reason.trim(), by: by.trim(), at, seen: i.seen }));
  const kept = a.decisions.filter((d) => !made.some((x) => x.item === d.item));
  const all = [...kept, ...made].sort((x, y) => (x.item < y.item ? -1 : x.item > y.item ? 1 : 0));
  writeJson(project.abs(FIDELITY_RECORD), { schema: 1, decisions: all });
  return made;
}

// ---- outcomes ---------------------------------------------------------------------------------

export interface Outcome {
  status: string;
  detail: string;
}

export interface Outcomes {
  validity: Outcome;
  generated: Outcome;
  coverage: Outcome;
  fidelity: Outcome & { unresolved: string[] };
}

const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;

async function validity(project: Project, adapters: AdapterSet): Promise<Outcome> {
  const run = async (c: typeof schemaCheck) => (await c.run({ project, adapters })) as CheckResult;
  const results = await Promise.all([schemaCheck, contrastCheck, chartPaletteCheck].map(run));
  const shown = results.filter((r) => r.status !== 'off');
  const detail = shown.map((r) => `${r.id} ${r.status.toUpperCase()}${r.status === 'fail' ? ` (${plural(r.findings.length, 'finding')})` : ''}`).join(', ');
  const status = results.some((r) => r.status === 'fail') ? 'fail' : results[0]!.status;
  return { status, detail: detail || results[0]!.reason || '' };
}

async function generated(project: Project, adapters: AdapterSet): Promise<Outcome> {
  const r = (await generatedCheck.run({ project, adapters })) as CheckResult;
  if (r.status === 'pass') return { status: 'current', detail: 'the CSS variables and the Tailwind theme match the tokens' };
  if (r.status === 'fail') return { status: 'stale', detail: r.findings.map((f) => `${f.file}: ${f.message}`).join('; ') };
  return { status: 'not built', detail: r.reason ?? '' };
}

const COMPONENT_WORDS: [RowStatus, string][] = [
  ['preserved', 'yours reused'],
  ['defaulted', 'fwos starter'],
  ['approximated', 'replaced'],
  ['unsupported', 'left out'],
];

function coverage(m: Mapping): Outcome {
  if (m.input === 'starter') return { status: 'none', detail: 'nothing adopted: the neutral starter' };
  const slots = m.tokens.filter((t) => t.target);
  const unconsumed = m.tokens.filter((t) => !t.target).length;
  const count = (rows: { status: RowStatus }[], s: RowStatus) => rows.filter((r) => r.status === s).length;
  const slotParts = (['preserved', 'approximated', 'defaulted', 'changed'] as RowStatus[]).filter((s) => count(slots, s) > 0).map((s) => `${count(slots, s)} ${s}`);
  const compParts = COMPONENT_WORDS.filter(([s]) => count(m.components, s) > 0).map(([s, word]) => `${count(m.components, s)} ${word}`);
  const detail = [`slots: ${slotParts.join(', ')}`, ...(unconsumed > 0 ? [`${unconsumed} source ${unconsumed === 1 ? 'entry' : 'entries'} not consumed`] : []), ...(compParts.length > 0 ? [`components: ${compParts.join(', ')}`] : [])].join('; ');
  const complete = slots.every((t) => t.status === 'preserved') && unconsumed === 0 && m.components.every((c) => c.status === 'preserved');
  return { status: complete ? 'complete' : 'partial', detail };
}

function fidelity(a: Assessment): Outcomes['fidelity'] {
  const unresolved = a.unresolved.map((i) => i.item);
  const need = unresolved.length > 0 ? ` ${plural(unresolved.length, 'item needs', 'items need')} a decision.` : '';
  if (a.mapping.input === 'starter') return { status: 'not applicable', detail: 'nothing was adopted, so there is no source to compare with', unresolved: [] };
  if (a.results.state === 'none') {
    const how = a.command ? `run \`fwos design-system gallery\`, then \`${a.command}\`` : 'no gallery for this platform';
    return { status: 'not compared', detail: `${a.results.reason}: ${how}.${need}`, unresolved };
  }
  if (a.results.state === 'stale') {
    return { status: 'out of date', detail: `the last comparison rendered an older design system or older components: run \`fwos design-system gallery\` and \`${a.command}\` again.${need}`, unresolved };
  }
  if (unresolved.length > 0) {
    const shown = unresolved.slice(0, 3).join(', ');
    return { status: 'unresolved', detail: `${plural(unresolved.length, 'item needs', 'items need')} a decision: ${shown}${unresolved.length > 3 ? ', ...' : ''}`, unresolved };
  }
  const r = a.render!;
  const same = [...r.summary.values()].reduce((n, s) => n + s.same, 0);
  const cells = [...r.summary.values()].reduce((n, s) => n + s.cells, 0);
  return { status: 'ready', detail: `compared, with every difference decided (${same} of ${cells} cells render the same): approve it with \`fwos approve fidelity --by "<name>"\``, unresolved };
}

// ---- the report -------------------------------------------------------------------------------

const code = (v: string) => `\`${v.replace(/\|/g, '\\|').replace(/`/g, "'")}\``;
const esc = (v: string) => v.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const perModeCell = (modes: string[], values: Record<string, string>, none = 'none') =>
  modes.every((m) => !values[m]) ? none : modes.map((m) => `${m} ${values[m] ? code(values[m]!) : 'none'}`).join('<br>');
const statusCell = (s: string, why: string) => esc(why ? `${s}: ${why}` : s);

function sourceSection(m: Mapping): string[] {
  if (m.input === 'starter') return ['Nothing was adopted: the design system is fwos\'s neutral starter, so every row below is fwos\'s.'];
  if (m.input === 'shadcn') {
    return [`Read from ${m.source}: its \`:root\` block and its dark block, as a browser applies them. Other blocks, such as \`@theme inline\`, aren't read.`];
  }
  return [`Read from your token files: ${m.source}. A conversion before fwos, from Tokens Studio, Figma or a Tailwind config, isn't compared: these files are the source.`];
}

function componentsSection(m: Mapping): string[] {
  if (m.components.length === 0) return ['No component registry, and no components installed.'];
  const list = (xs: { name: string }[] | undefined) => (xs && xs.length > 0 ? esc(xs.map((x) => x.name).join(', ')) : '-');
  const variants = (row: ComponentRow) => (row.facts && row.facts.variants.length > 0 ? esc(row.facts.variants.map((v) => `${v.name}: ${v.values.join(', ')}`).join('; ')) : '-');
  return [
    'Read from each component\'s source, without running it: its exports, variant axes, the states it can render and what a person can do with it. A replacement or an omission needs a decision.',
    '',
    '| Component | Yours | Becomes | Variants | States | Interactions | Status |',
    '|---|---|---|---|---|---|---|',
    ...m.components.map((c) => {
      const yours = c.source ? `${esc(c.source.file)}${c.source.exports.length ? ` (${esc(c.source.exports.join(', '))})` : ''}` : 'none';
      const becomes = c.target ? `${code(c.target.id)} (${c.target.by === 'fwos' ? "fwos's" : 'yours'}${c.target.file ? `, ${esc(c.target.file)}` : ', not installed'})` : 'nothing';
      return `| ${code(c.key)} | ${yours} | ${becomes} | ${variants(c)} | ${list(c.facts?.states)} | ${list(c.facts?.interactions)} | ${statusCell(c.status, c.why)} |`;
    }),
  ];
}

/** Property names, with the four sides of a box written once: `border-color` for its four sides. */
function collapse(props: string[]): string[] {
  const set = new Set(props);
  for (const [whole, parts] of [
    ['border-color', ['border-top-color', 'border-right-color', 'border-bottom-color', 'border-left-color']],
    ['border-width', ['border-top-width', 'border-right-width', 'border-bottom-width', 'border-left-width']],
    ['border-radius', ['border-top-left-radius', 'border-top-right-radius', 'border-bottom-right-radius', 'border-bottom-left-radius']],
    ['padding', ['padding-top', 'padding-right', 'padding-bottom', 'padding-left']],
  ] as const) {
    for (const prefix of ['', 'hover: ', 'focus: ', 'open: ']) {
      if (parts.every((x) => set.has(prefix + x))) {
        for (const x of parts) set.delete(prefix + x);
        set.add(prefix + whole);
      }
    }
  }
  return [...set].sort((x, y) => (x.includes(':') ? 1 : 0) - (y.includes(':') ? 1 : 0) || (x < y ? -1 : x > y ? 1 : 0));
}

const KIND_WORDS: Record<GalleryEntry['kind'], string> = {
  reused: 'yours, on both sides',
  starter: "fwos's, with your source's values on the original side",
  replaced: 'yours, then its replacement',
  omitted: 'yours, original side only',
};

function renderedSection(a: Assessment): string[] {
  const tokens = new Map(a.mapping.tokens.map((t) => [t.key, t]));
  const how = a.command ? `\`fwos design-system gallery\` writes the gallery into your app, and \`${a.command}\` renders both sides in Chromium` : 'This platform has no gallery yet, so nothing renders';
  if (!a.model) return ['Nothing to render: nothing was adopted.'];
  if (a.results.state === 'none') return [`No rendered comparison yet. ${how}, in each mode at ${VIEWPORTS.map((v) => `${v.width}`).join(' and ')} pixels wide, and writes \`${FIDELITY_RESULTS}\` with screenshots in \`${GALLERY_SHOTS}/\`.`];
  if (a.results.state === 'stale') return [`The last comparison rendered an older design system or older components, so it says nothing about this one. ${how} again.`];
  const r = a.render!;
  const out = [
    `Rendered in ${esc(a.results.results.browser)}, in ${a.model.modes.join(' and ')} at ${VIEWPORTS.map((v) => `${v.width}`).join(' and ')} pixels wide. A cell is one variant or state of one component, in one mode at one width. The original side sets your source's values and the adopted side the design system fwos holds; a cell renders the same when every computed style and every interaction matches.`,
    '',
    '| Component | Shown as | Cells | Same | Behaviour differs |',
    '|---|---|---|---|---|',
    ...[...r.summary].map(([id, s]) => `| ${code(id)} | ${KIND_WORDS[s.kind]} | ${s.cells} | ${s.same} | ${s.behaviour} |`),
  ];
  if (r.errors.length > 0) out.push('', '### Page errors', '', ...r.errors.map((e) => `- ${esc(e)}`));
  if (r.differences.length > 0) {
    // One row per component, value change and cause: the properties and cells it shows in, together.
    const groups = new Map<string, { d: Difference; props: Set<string>; where: Map<string, Set<string>> }>();
    for (const d of r.differences) {
      const key = JSON.stringify([d.component, d.original, d.adopted, d.rows]);
      const g = groups.get(key) ?? { d, props: new Set<string>(), where: new Map<string, Set<string>>() };
      const state = /^(hover|focus|open):/.exec(d.element)?.[1];
      g.props.add(`${state ? `${state}: ` : ''}${d.property}`);
      g.where.set(d.cell.cell, (g.where.get(d.cell.cell) ?? new Set<string>()).add(`${d.cell.mode} ${d.cell.viewport}`));
      groups.set(key, g);
    }
    // Each difference is intentional once what accounts for it is decided, and unresolved until then.
    const open = new Set(a.unresolved.map((i) => i.item));
    const decision = new Map(a.decisions.map((d) => [d.item, d]));
    const verdict = (items: string[]) => (items.every((i) => !open.has(i)) ? `intentional: ${[...new Set(items.map((i) => decision.get(i)?.reason ?? ''))].filter(Boolean).join('; ')}` : 'needs a decision');
    const rows = [...groups.values()].map(({ d, props, where }) => {
      const kind = r.summary.get(d.component)!.kind;
      const covers = d.rows.length > 0 ? d.rows : kind === 'replaced' || kind === 'omitted' ? [d.component] : [`render:${d.component}`];
      const named = d.rows.length > 0 ? d.rows.map((row) => `${code(row)} (${tokens.get(row)?.status ?? 'row'})`).join(', ') : kind === 'replaced' || kind === 'omitted' ? `${code(d.component)} (${kind})` : `nothing, so ${code(`render:${d.component}`)}`;
      return { d, props, where, settled: covers.every((i) => !open.has(i)), by: `${named}, ${verdict(covers)}` };
    });
    const intentional = rows.filter((x) => x.settled).length;
    out.push(
      '',
      `Faithful: ${[...r.summary.values()].reduce((n, s) => n + s.same, 0)} of ${[...r.summary.values()].reduce((n, s) => n + s.cells, 0)} cells render the same on both sides.`,
      `Intentional: ${intentional === 1 ? '1 difference' : `${intentional} differences`}, accounted for by a row someone decided.`,
      `Unresolved: ${rows.length - intentional === 1 ? '1 difference waits' : `${rows.length - intentional} differences wait`} on a decision.`,
      '',
      '### Differences',
      '',
      'One row per component and change: the cells it shows in (with the modes and widths), and the properties it changes there.',
      '',
      '| Component | Cells | Properties | Original | Adopted | Accounted for by |',
      '|---|---|---|---|---|---|',
    );
    for (const { d, props, where, by } of rows) {
      const cells = [...where].map(([cell, at]) => `${code(cell)} (${[...at].join(', ')})`);
      const shown = cells.length > 4 ? `${cells.slice(0, 4).join(', ')} and ${cells.length - 4} more` : cells.join(', ');
      out.push(`| ${code(d.component)} | ${shown} | ${esc(collapse([...props]).join(', '))} | ${code(d.original)} | ${code(d.adopted)} | ${esc(by)} |`);
    }
  } else {
    out.push('', `Faithful: every one of the ${[...r.summary.values()].reduce((n, s) => n + s.cells, 0)} cells renders the same on both sides.`);
  }
  if (r.behaviour.length > 0) {
    out.push('', '### Behaviour', '', '| Component | Cell | Interaction | Original | Adopted |', '|---|---|---|---|---|');
    for (const b of r.behaviour) out.push(`| ${code(b.component)} | ${esc(`${b.cell.cell} (${b.cell.mode}, ${b.cell.viewport})`)} | ${b.interaction} | ${esc(b.original)} | ${esc(b.adopted)} |`);
  }
  return out;
}

function decisionsSection(a: Assessment): string[] {
  const out: string[] = [];
  const stale = new Set(a.stale.map((d) => d.item));
  out.push('## Needs a decision', '');
  if (a.mapping.input === 'starter') out.push('Nothing: nothing was adopted.');
  else if (a.unresolved.length === 0) out.push('Nothing: every row that isn\'t preserved, every replacement and every difference is decided.');
  else {
    out.push(
      'Each of these needs a decision before the fidelity approval: `fwos design-system decide <item> --as <decision> --reason "<why>" --by "<name>"`. A status in place of the item (`defaulted`) takes every undecided item of it that the decision fits.',
      '',
      '| Item | What | Decide |',
      '|---|---|---|',
      ...a.unresolved.map((i) => `| ${code(i.item)} | ${esc(i.what)}${stale.has(i.item) ? ' (decided before it changed)' : ''} | ${i.needs.length ? i.needs.join(' or ') : 'a clean run'} |`),
    );
  }
  out.push('', '## Decisions', '');
  const current = a.decisions.filter((d) => !a.orphans.includes(d));
  if (current.length === 0) out.push('None yet.');
  else {
    out.push('| Item | Decision | Reason | By | At |', '|---|---|---|---|---|');
    for (const d of current) out.push(`| ${code(d.item)} | ${d.decision}${stale.has(d.item) ? ' (it changed since)' : ''} | ${esc(d.reason)} | ${esc(d.by)} | ${d.at.slice(0, 10)} |`);
  }
  if (a.orphans.length > 0) out.push('', `No longer applies, since nothing by that name needs a decision now: ${a.orphans.map((d) => code(d.item)).join(', ')}.`);
  return out;
}

function markdown(a: Assessment, o: Outcomes): string {
  const m = a.mapping;
  const slots = m.tokens.filter((t) => t.target);
  const unconsumed = m.tokens.filter((t) => !t.target);
  const route = a.command ? `\`${GALLERY_ROUTE}\` in \`pnpm dev\`` : 'the gallery';
  return [
    REPORT_HEADER,
    '',
    `# Design-system adoption: ${esc(m.name)}`,
    '',
    "This maps your source design system onto fwos's slots and components, and records how the adopted result renders next to the original. A PASS from `design-system/schema` and `design-system/contrast` means the tokens are valid and their text readable. It doesn't compare them with your source, so read the coverage and fidelity rows too.",
    '',
    '## Outcomes',
    '',
    '| Outcome | Now | What it says |',
    '|---|---|---|',
    `| Token validity | ${o.validity.status.toUpperCase()} | ${esc(o.validity.detail)}. It says the tokens are valid and readable, not that they match your source. |`,
    `| Generated CSS | ${o.generated.status} | ${esc(o.generated.detail)}. |`,
    `| Adoption coverage | ${o.coverage.status} | ${esc(o.coverage.detail)}. |`,
    `| Fidelity | ${o.fidelity.status} | ${esc(o.fidelity.detail)} |`,
    '| Preview | - | `/fwos-screens` shows the app on fake data. It compares nothing with your source. |',
    '',
    'The fidelity approval is a hash of this file, so it isn\'t in it: `fwos status` shows it.',
    '',
    '## Source',
    '',
    ...sourceSection(m),
    '',
    '## Tokens',
    '',
    '| Slot | Source | Original | Result | Status |',
    '|---|---|---|---|---|',
    ...slots.map((t) => `| ${code(t.key)} | ${t.source ? `${code(t.source.key)} in ${esc(t.source.file)}` : 'none'} | ${perModeCell(m.modes, t.original)} | ${perModeCell(m.modes, t.result, 'blank')} | ${statusCell(t.status, t.why)} |`),
    '',
    '## Not consumed',
    '',
    ...(unconsumed.length === 0
      ? ['Nothing: every entry the source has reaches a slot.']
      : ['| Key | File | Original | Status |', '|---|---|---|---|', ...unconsumed.map((t) => `| ${code(t.key)} | ${esc(t.source!.file)} | ${perModeCell(m.modes, t.original)} | ${statusCell(t.status, t.why)} |`)]),
    '',
    '## Components',
    '',
    ...componentsSection(m),
    '',
    '## Rendered comparison',
    '',
    ...renderedSection(a),
    '',
    ...decisionsSection(a),
    '',
    '## How to inspect it',
    '',
    `- Open ${route}: each component sits in two frames, the original and the adopted, with links to each mode and width.`,
    '- Check each variant and state in both modes and at phone width: colour, borders, radius, type, focus ring, and what hover, press, open or check does.',
    `- The comparison writes screenshots of each side to \`${GALLERY_SHOTS}/\`, and every difference above names the rows that account for it.`,
    '- Decide each item above, run `fwos design-system report` again, then `fwos approve fidelity --by "<name>"`. Any later change to the design system makes that approval stale.',
    '',
  ].join('\n');
}

export interface AdoptionReport {
  markdown: string;
  outcomes: Outcomes;
  mapping: Mapping;
  unresolved: Item[];
}

/** The mapping, the component inventory, the rendered comparison and the outcomes, as one deterministic report. */
export async function adoptionReport(project: Project, adapters: AdapterSet): Promise<AdoptionReport> {
  const a = assess(project, adapters);
  const outcomes: Outcomes = {
    validity: await validity(project, adapters),
    generated: await generated(project, adapters),
    coverage: coverage(a.mapping),
    fidelity: fidelity(a),
  };
  return { markdown: markdown(a, outcomes), outcomes, mapping: a.mapping, unresolved: a.unresolved };
}

/** The four outcomes and the preview, as aligned lines for a terminal. */
export function formatOutcomes(o: Outcomes): string[] {
  const row = (label: string, status: string, detail: string) => `${label.padEnd(19)}${status.padEnd(13)} ${detail}`;
  return [
    row('Token validity', o.validity.status.toUpperCase(), o.validity.detail),
    row('Generated CSS', o.generated.status, o.generated.detail),
    row('Adoption coverage', o.coverage.status, o.coverage.detail),
    row('Fidelity', o.fidelity.status, o.fidelity.detail),
    row('Preview', '-', '/fwos-screens shows the app on fake data. It compares nothing with your source.'),
  ];
}

