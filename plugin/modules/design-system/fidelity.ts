// Fidelity: how an adopted design system renders next to its source. The gallery model says what
// each side sets; a platform renders both and writes what differs. Every row, component or
// rendered difference that isn't preserved needs a decision a person records with a reason, and
// the report keeps four outcomes apart: token validity, generated CSS, adoption coverage and
// fidelity. None of them stands in for another, and the report never says it was approved, since
// the fidelity approval is a hash of it.

