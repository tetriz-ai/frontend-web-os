// Platform outputs generated from the design system. Web and Electron get CSS variables (one per
// slot, so component code is identical across design systems) and a Tailwind v4 theme that
// exposes only the slots: the default palette is cleared, so `bg-red-500` simply doesn't exist.

import { posix } from 'node:path';
import type { GeneratedFile, Project } from '../../kernel/index.ts';
import type { DesignSystem, ResolvedSlot } from './load.ts';
import { SLOTS, cssVar } from './slots.ts';

export const GENERATED_HEADER = (ds: DesignSystem) =>
  `/* generated by fwos, do not edit. source: ${ds.dir}/ (${ds.config.name}). Run \`fwos tokens build\` after changing tokens. */`;

function decls(slot: ResolvedSlot, mode: string): string[] {
  if (slot.status === 'default' && typeof slot.from === 'string' && slot.from.startsWith('@')) {
    // Keep the relationship, so the fallback follows every mode.
    return [`${cssVar(slot.def.id)}: var(${cssVar(slot.from.slice(1))});`];
  }
  return (slot.css[mode] ?? []).map((d) => `${cssVar(slot.def.id)}${d.suffix}: ${d.value};`);
}

export function tokensCss(ds: DesignSystem): string {
  const live = SLOTS.map((d) => ds.slots.get(d.id)!).filter((s) => s && s.status !== 'blank');
  const base = ds.defaultMode;
  const lines = [GENERATED_HEADER(ds), '', ':root {', `  color-scheme: ${base === 'dark' ? 'dark' : 'light'};`];
  for (const s of live) for (const d of decls(s, base)) lines.push(`  ${d}`);
  lines.push('}');
  for (const mode of ds.modes) {
    if (mode === base) continue;
    const changed = live.flatMap((s) => {
      const a = decls(s, base);
      const b = decls(s, mode);
      return a.join() === b.join() ? [] : b;
    });
    const scheme = mode === 'dark' ? 'dark' : mode === 'light' ? 'light' : null;
    const body = [...(scheme ? [`color-scheme: ${scheme};`] : []), ...changed];
    if (mode === 'dark' && base !== 'dark') {
      lines.push('', '@media (prefers-color-scheme: dark) {', `  :root:not([data-theme]) {`);
      for (const d of body) lines.push(`    ${d}`);
      lines.push('  }', '}');
    }
    lines.push('', `:root[data-theme="${mode}"] {`);
    for (const d of body) lines.push(`  ${d}`);
    lines.push('}');
  }
  lines.push('', `:root[data-theme="${base}"] {`, `  color-scheme: ${base === 'dark' ? 'dark' : 'light'};`, '}');
  return `${lines.join('\n')}\n`;
}

export function themeCss(ds: DesignSystem): string {
  const lines = [
    GENERATED_HEADER(ds),
    '/* Tailwind v4 theme: only the design-system slots exist as utilities. */',
    '',
    '@theme {',
    '  --color-*: initial;',
    '  --radius-*: initial;',
    '  --text-*: initial;',
    '}',
    '',
    '@theme inline {',
    '  --color-transparent: transparent;',
    '  --color-current: currentColor;',
  ];
  for (const def of SLOTS) {
    const s = ds.slots.get(def.id);
    if (!s || s.status === 'blank' || !def.tailwind) continue;
    const v = cssVar(def.id);
    if (def.type === 'typography') {
      lines.push(`  --${def.tailwind}: var(${v}-size);`);
      const sample = s.css[ds.defaultMode] ?? [];
      if (sample.some((d) => d.suffix === '-line')) lines.push(`  --${def.tailwind}--line-height: var(${v}-line);`);
      if (sample.some((d) => d.suffix === '-weight')) lines.push(`  --${def.tailwind}--font-weight: var(${v}-weight);`);
      if (sample.some((d) => d.suffix === '-tracking')) lines.push(`  --${def.tailwind}--letter-spacing: var(${v}-tracking);`);
    } else {
      lines.push(`  --${def.tailwind}: var(${v});`);
    }
  }
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

export function tokenOutputs(project: Project, ds: DesignSystem): GeneratedFile[] {
  const out = project.paths.tokensOut;
  const source = `${ds.dir}/`;
  return [
    { path: posix.join(out, 'tokens.css'), content: tokensCss(ds), source },
    { path: posix.join(out, 'theme.css'), content: themeCss(ds), source },
  ];
}
